import path from "node:path";
import type { NextConfig } from "next";

/**
 * Админка — отдельное приложение, и намеренно.
 *
 * Сам сайт собирается в статику (output: "export"): ни сервера, ни базы,
 * переносится на любой хостинг копированием папки. Админке же нужен сервер:
 * она коммитит правки в репозиторий своим токеном, а держать токен в
 * браузере нельзя. Смешивать одно с другим значило бы лишить сайт главного
 * его свойства ради панели, которой пользуются пару раз в месяц.
 */
const nextConfig: NextConfig = {
  // Корень — сама папка admin/, а не весь репозиторий. Иначе Turbopack
  // подхватывает postcss.config.mjs сайта с Tailwind, которого у админки
  // нет в зависимостях: локально это прячут node_modules сайта в корне,
  // а на хостинге, где ставятся только зависимости админки, сборка падает.
  turbopack: { root: path.resolve(__dirname) },
  outputFileTracingRoot: path.resolve(__dirname),

  // По умолчанию server action принимает не больше 1 МБ: фото с телефона
  // в новость не проходило, и редактор видел страницу сбоя. Файлы до 4 МБ
  // (lib/save.ts) плюс запас на остальные поля формы. Больше Vercel всё
  // равно не пропустит: его предел на запрос — 4,5 МБ.
  experimental: { serverActions: { bodySizeLimit: "4.4mb" } },
};

export default nextConfig;
