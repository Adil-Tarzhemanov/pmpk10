import { Golos_Text } from "next/font/google";

/**
 * Golos Text (ParaType) — гротеск, нарисованный от кириллицы, а не
 * приспособленный под неё. В нём есть подмножество cyrillic-ext, где живут
 * казахские ә ғ қ ң ө ұ ү һ: без него казахская версия сайта рассыпалась бы
 * на подстановки из системных гарнитур.
 *
 * Одна гарнитура на весь сайт, заголовки отличаются насыщенностью и трекингом.
 * Вариативное начертание — весь диапазон 400–900 приходит одним файлом, так
 * что лишние запросы за отдельными весами не нужны.
 *
 * next/font скачивает файлы на этапе сборки и раздаёт с нашего домена:
 * внешних запросов к Google нет — это и быстрее, и чище по приватности.
 *
 * Лежит отдельным модулем, потому что корневых layout'ов у нас два:
 * страница выбора языка и сам сайт. Шрифт у них общий.
 */
export const golos = Golos_Text({
  subsets: ["cyrillic-ext", "cyrillic", "latin"],
  variable: "--font-golos",
  display: "swap",
});

/** Класс с CSS-переменной шрифта — вешается на <html> */
export const fontVariables = golos.variable;
